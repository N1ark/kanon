(* Classification *)

type kind = Rule | OHelper | Pure
type ctx = { prims : prim list; kinds : (string * kind) list; fns : fn list }

let fn_kind ctx f = List.assoc f ctx.kinds
let is_oracle ctx f = List.exists (fun p -> p.pname = f && p.oracle) ctx.prims
let is_prim ctx f = List.exists (fun p -> p.pname = f) ctx.prims

(** The program without its [[@no_lean]] functions and primitives, which Lean
    does not see: nothing that it models calls them (see [Check.program]). *)
let modelled (p : program) =
  {
    p with
    prims = List.filter (fun (q : prim) -> not q.pno_lean) p.prims;
    fns = List.filter (fun (f : fn) -> not f.no_lean) p.fns;
  }

let classify (p : program) =
  let is_oracle f = List.exists (fun q -> q.pname = f && q.oracle) p.prims in
  let kinds =
    ref
      (List.map
         (fun f -> (f.name, if Option.is_some f.spec then Rule else Pure))
         p.fns)
  in
  let changed = ref true in
  while !changed do
    changed := false;
    List.iter
      (fun f ->
        if List.assoc f.name !kinds = Pure then
          let needs_o =
            List.exists
              (fun g ->
                is_oracle g
                ||
                match List.assoc_opt g !kinds with
                | Some (Rule | OHelper) -> true
                | _ -> false)
              (Gen_ocaml.calls [] f.body)
          in
          if needs_o then (
            kinds := (f.name, OHelper) :: List.remove_assoc f.name !kinds;
            changed := true))
      p.fns
  done;
  { prims = p.prims; kinds = !kinds; fns = p.fns }

(* ---------------------------------------------------------------- *)
(* Modules proved once ([[@@@lean_module]])

   The files of such a module are printed over its interface rather than over
   the terms of a language: [generic] is then set, and the nodes, sorts,
   primitives and helpers are the fields of the interface [L] (or of the
   structure being declared, unprefixed), the types of terms and sorts those of
   any semantics [S]. *)

(** What the expressions are printed over, when they are over an interface: the
    module [self] whose files are printed, and whether in the structure that
    declares its interface ([inside], where its own fields are unprefixed). *)
type gen = { self : string; inside : bool }

let generic : gen option ref = ref None

(** [k ()], printed over the interface of the module [self]. *)
let over_interface ?(inside = false) self k =
  let saved = !generic in
  generic := Some { self; inside };
  Fun.protect ~finally:(fun () -> generic := saved) k

(** The variable of the interface of the module [m], in the files of a module:
    [L] for the module itself, [LM] for a module [M] that it uses. *)
let lvar m =
  match !generic with Some { self; _ } when self = m -> "L" | _ -> "L" ^ m

(** The field [x] of the interface of the module [m] ([None]: of the language,
    [Kanon.Base]). *)
let gfield_of m x =
  match (m, !generic) with
  | None, _ -> "B." ^ x
  | Some m, Some { self; inside = true } when m = self -> x
  | Some m, _ -> lvar m ^ "." ^ x

(** What cannot be stated over the interface of a module: reported at [loc]. *)
let unsupported loc fmt =
  Fmt.kstr
    (fun s ->
      raise
        (Check.Error
           ( loc,
             s
             ^ ": not in the Lean interface of its module ([@@@lean_module]); \
                mark its rule [@lean_closed], or prove the module per language"
           )))
    fmt

(** The root of the Lean files of the module [m], if it is proved once. *)
let module_root m = List.assoc_opt m !lang.lean_modules

let is_generic_module m = Option.is_some (module_root m)

(** The module of an item declared at [loc]. *)
let module_of_loc (loc : Location.t) =
  try Check.module_of_loc loc with Check.Error _ -> None

(** The module of the function, primitive or constant [name]. *)
let module_of_name name = Option.map fst (split_name name)

(** The field [x] of the interface of the module of the constructor [c]. *)
let cfield (c : constr) x =
  match module_of_loc c.c_loc with
  | Some m -> gfield_of (Some m) x
  | None -> gfield_of (Option.map (fun g -> g.self) !generic) x

(** The field [x] of the interface of the module of the item [name]. *)
let nfield name x = gfield_of (module_of_name name) x

(** The name of the field of the kind of a node [C] in an interface: [CK]. *)
let kind_field c = c ^ "K"

