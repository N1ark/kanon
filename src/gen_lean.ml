(** The invariant of a sort or a node ([[@lean_inv "P"]]), if it has one. *)
let inv_of (c : constr) = List.assoc_opt c.c_name !lang.lean_invs

(** The sorts and nodes of the module [m] that have an invariant, with it. *)
let module_invs m =
  List.filter_map
    (fun (c : constr) ->
      if in_module m c.c_loc then Option.map (fun p -> (c, p)) (inv_of c)
      else None)
    !lang.constrs

(** The typing law of the node [n] (in a structure: unprefixed): its typing, by
    its sorts; its operands, and the terms of its arguments, are well-typed; and
    its invariant and that of its sort hold ([[@lean_inv]]). *)
let wt_law ctx (p : program) (n : gnode) =
  let xs, os = node_names p n in
  let t = "t" in
  let term = gnode_term n (xs @ os) t in
  let bs =
    binders
      (List.combine xs n.gpayload @ List.combine os n.goperands @ [ (t, TSty) ])
  in
  let ty = node_typing p n in
  let nary =
    List.exists (function TList _ -> true | _ -> false) n.goperands
  in
  let typing =
    match ty with
    | None -> []
    | Some ty when nary ->
        let l = List.hd os in
        [
          Printf.sprintf "∃ e, (%s) ∧ ∀ x ∈ %s, S.ty x = e ∧ S.WT x"
            (typing_rhs ~names:[ "e"; t ] ctx ty)
            l;
        ]
    | Some ty when n.goperands = [] -> [ typing_rhs ~names:[ t ] ctx ty ]
    | Some ty ->
        let names = List.map (fun a -> "(S.ty " ^ a ^ ")") os @ [ t ] in
        ("(" ^ typing_rhs ~names ctx ty ^ ")")
        :: List.map (fun a -> "S.WT " ^ a) os
  in
  let args =
    List.filter_map
      (fun (x, ty) ->
        match ty with
        | TTerm -> Some ("S.WT " ^ x)
        | TList TTerm -> Some (Printf.sprintf "(∀ y ∈ %s, S.WT y)" x)
        | _ -> None)
      (List.combine xs n.gpayload)
  in
  let inv (c : constr) =
    Option.map (fun q -> Printf.sprintf "%s %s" (cfield c q) term) (inv_of c)
  in
  let sort_inv =
    match ty with
    | Some ty -> (
        match (List.hd (List.rev ty.t_sorts)).e with
        | EConstr (c, _) -> inv c
        | _ -> None)
    | None -> None
  in
  let extra = args @ Option.to_list (inv n.gc) @ Option.to_list sort_inv in
  let typing =
    match typing with
    | [ x ] when nary && extra <> [] -> [ "(" ^ x ^ ")" ]
    | l -> l
  in
  let rhs =
    match typing @ extra with [] -> "True" | l -> String.concat " ∧ " l
  in
  Printf.sprintf "WT_%s : ∀ %s, S.WT %s ↔ %s" n.gc.c_name bs term rhs

(** The fields of the matcher of the node [n], and its laws. *)
let matcher_fields (p : program) (n : gnode) =
  let xs, os = node_names p n in
  let args = xs @ os in
  let tys = n.gpayload @ n.goperands in
  let c = n.gc.c_name in
  let bs = binders (List.combine args tys) in
  [
    Printf.sprintf "/-- The arguments of a `%s` node. -/" c;
    Printf.sprintf "as%s : S.Term → Option %s" c (tuple_ty tys);
    Printf.sprintf "as%s_node : ∀ %s (t : S.Ty), as%s %s = some %s" c bs c
      (gnode_term n args "t") (tuple args);
    Printf.sprintf "as%s_sound : ∀ (v : S.Term) %s, as%s v = some %s → v = %s" c
      bs c (tuple args)
      (gnode_term n args "(S.ty v)");
  ]

(** The fields of the matcher of the sort [c] (of the interface of its module),
    and its laws. *)
let sort_matcher_fields (c : constr) =
  let xs =
    List.mapi (fun i a -> (Printf.sprintf "x%d" (i + 1), arg_ty a)) c.c_args
  in
  let args = List.map fst xs in
  let n = c.c_name in
  let bs = if xs = [] then "" else "∀ " ^ binders xs ^ ", " in
  [
    Printf.sprintf "/-- The arguments of the sort `%s`. -/" n;
    Printf.sprintf "as%s : S.Ty → Option %s" n (tuple_ty (List.map snd xs));
    Printf.sprintf "as%s_sort : %sas%s %s = some %s" n bs n (app n args)
      (tuple args);
    Printf.sprintf "as%s_sound : ∀ (s : S.Ty)%s, as%s s = some %s → s = %s" n
      (if xs = [] then "" else " " ^ binders xs)
      n (tuple args) (app n args);
  ]

(** The sort laws: the sorts of [m] differ from each other and from those of the
    modules it uses, and are injective in their arguments. *)
let sort_laws m =
  let own = module_sorts m in
  let others =
    List.concat_map module_sorts (List.filter (( <> ) m) (generic_closure m))
  in
  let args prefix (c : constr) =
    List.mapi
      (fun i a -> (Printf.sprintf "%s%d" prefix (i + 1), arg_ty a))
      c.c_args
  in
  let sort (c : constr) xs = app (cfield c c.c_name) (List.map fst xs) in
  let rec pairs = function
    | [] -> []
    | c :: rest -> List.map (fun d -> (c, d)) (rest @ others) @ pairs rest
  in
  List.map
    (fun ((a : constr), (b : constr)) ->
      let xs = args "x" a and ys = args "y" b in
      let bs = xs @ ys in
      Printf.sprintf "%s_ne_%s : %s%s ≠ %s" a.c_name b.c_name
        (if bs = [] then "" else "∀ " ^ binders bs ^ ", ")
        (sort a xs) (sort b ys))
    (pairs own)
  @ List.filter_map
      (fun (c : constr) ->
        if c.c_args = [] then None
        else
          let xs = args "x" c and ys = args "y" c in
          Some
            (Printf.sprintf "%s_inj : ∀ %s, %s = %s → %s" c.c_name
               (binders (xs @ ys))
               (sort c xs) (sort c ys)
               (String.concat " ∧ "
                  (List.map2 (fun (x, _) (y, _) -> x ^ " = " ^ y) xs ys))))
      own

(** A helper as a field: its name and type. *)
let helper_field (f : fn) = Fmt.str "%s : %a" (fld f.name) arrow f

(** The equation of a helper, as a field: its body, over the interface. *)
let helper_eq ctx ~o ft (f : fn) =
  let lhs = if o then "O." ^ fld f.name else nfield f.name (fld f.name) in
  pf ft "  @[<hv 4>%s_eq : %s%s =@ %a@]@ " (fld f.name)
    (if f.params = [] then "" else Fmt.str "∀ %a, " params f)
    (app lhs (List.map (fun (x, _) -> id x) f.params))
    (expr ctx) f.body

let syntax_file ctx (p : program) m =
  with_root (groot m) @@ fun () ->
  let deps = generic_deps m in
  lean_file ~sources:(module_sources m) [ "Syntax" ]
    (("KanonCore.Generic" :: types_imports ~abstract:true [ m ])
    @ List.map (fun d -> groot d ^ ".Syntax") deps)
  @@ fun ft ->
  over_interface ~inside:true m @@ fun () ->
  lines ft
    [
      Printf.sprintf
        "/-- What the module `%s` needs of the terms `B` of a language of \
         semantics `S`, whose"
        m;
      "modules that it uses have the interfaces of the parameters: Kanon \
       generates it, and each";
      "language that uses the module gives it, by definition. -/";
      Printf.sprintf "structure Syntax {S : Kanon.Sem} %s %s where" deq
        (iface_binders ~explicit:true m);
    ];
  let field x = pf ft "  %s@ " x in
  List.iter
    (fun (c : constr) ->
      Option.iter (fun d -> pf ft "  %a" doc (Some d)) c.c_doc;
      field
        (Fmt.str "%s : %a" c.c_name
           (fun ft () ->
             List.iter (fun a -> pf ft "%a → " lean_ty (arg_ty a)) c.c_args;
             pf ft "S.Ty")
           ()))
    (module_sorts m);
  List.iter field (sort_laws m);
  let nodes = module_nodes m in
  List.iter
    (fun n ->
      Option.iter (fun d -> pf ft "  %a" doc (Some d)) n.gc.c_doc;
      field
        (Fmt.str "%s : %a%s" (kind_field n.gc.c_name)
           (fun ft () ->
             List.iter
               (fun t -> pf ft "%a → " lean_ty t)
               (n.gpayload @ n.goperands))
           () (gfield_of None "Kind")))
    nodes;
  List.iter
    (fun ((c : constr), q) ->
      pf ft "  /-- The invariant of the terms of `%s`. -/@ " c.c_name;
      field (q ^ " : S.Term → Prop"))
    (module_invs m);
  List.iter (fun n -> field (wt_law ctx p n)) nodes;
  List.iter (fun n -> List.iter field (matcher_fields p n)) nodes;
  List.iter (fun c -> List.iter field (sort_matcher_fields c)) (module_sorts m);
  List.iter
    (fun ss ->
      Option.iter (fun d -> pf ft "  %a" doc (Some d)) ss.ss_doc;
      field (Option.get ss.ss_lean ^ " : S.Term → Prop"))
    (module_subsorts m);
  List.iter
    (fun (q : prim) ->
      Option.iter (fun d -> pf ft "  %a" doc (Some d)) q.pdoc;
      field
        (Fmt.str "%s : %a%a" (fld q.pname)
           (fun ft () -> List.iter (fun t -> pf ft "%a → " lean_ty t) q.pargs)
           () lean_ty q.pret))
    (module_prims ctx m);
  let helpers = module_helpers ctx m Pure in
  List.iter
    (fun (f : fn) ->
      Option.iter (fun d -> pf ft "  %a" doc (Some d)) f.fdoc;
      field (helper_field f))
    helpers;
  List.iter
    (fun (f : fn) -> if not f.extensible then helper_eq ctx ~o:false ft f)
    helpers;
  pf ft "@ "

