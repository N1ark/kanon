(* The modules proved once ([[@@@lean_module "R"]]), see [module_files] *)

(** [x] applied to the parameters of the semantics, as an argument. *)
let with_sem_args x =
  if !lang.lean_params = [] then x else "(" ^ x ^ sem_args () ^ ")"

(** The modules that each module uses, by name, as the command line reads them
    (see {!Loader.load}). *)
let module_uses : (string * string list) list ref = ref []

(** The modules built into kanon: their Lean files are in Kanon's library, and
    the languages that use them do not generate them. *)
let builtin_modules : string list ref = ref []

(** The lines [l], each followed by a break. *)
let lines ft l = List.iter (fun x -> pf ft "%s@ " x) l

(** The modules whose nodes, sorts and functions each module refers to, by
    module (see [compute_refs]). *)
let module_refs : (string * string list) list ref = ref []

(** Records the modules that each module refers to in [p]: in its functions, in
    the cases it adds to the functions of others (and those functions), and in
    the typing of its nodes. *)
let compute_refs (p : program) =
  let refs = ref [] in
  let add m d =
    match (m, d) with
    | Some m, Some d when m <> d && not (List.mem (m, d) !refs) ->
        refs := (m, d) :: !refs
    | _ -> ()
  in
  let constr m (c : constr) = add m (module_of_loc c.c_loc) in
  let rec pat m (q : pat) =
    match q.p with
    | PConstr (c, l) ->
        constr m c;
        List.iter (pat m) l
    | PAs (q, _) | PSome q -> pat m q
    | PTuple l -> List.iter (pat m) l
    | PCons (a, b) | POr (a, b) | PComm (a, b) ->
        pat m a;
        pat m b
    | PRecord fs -> List.iter (fun (_, q) -> pat m q) fs
    | _ -> ()
  in
  let rec expr m (e : expr) =
    let go = expr m in
    match e.e with
    | EConstr (c, l) ->
        constr m c;
        List.iter go l
    | ECall (f, l) ->
        add m (module_of_name f);
        List.iter go l
    | ELocalCall (_, l) | ETuple l | EArray l -> List.iter go l
    | ENode (a, b) | EBinop (_, a, b) | ECons (a, b) | EAssert (a, b) ->
        go a;
        go b
    | EUnop (_, a) | ESome a | EField (a, _) -> go a
    | EIf (a, b, c) ->
        go a;
        go b;
        go c
    | ERecord l -> List.iter (fun (_, e) -> go e) l
    | ELet (q, a, b) ->
        pat m q;
        go a;
        go b
    | ELetFun (_, _, a, b) ->
        go a;
        go b
    | EMatch (scruts, cases) ->
        List.iter go scruts;
        List.iter
          (fun (c : case) ->
            let m' =
              match module_of_loc c.cloc with Some m' -> Some m' | None -> m
            in
            (* a case that a module adds to a function of another *)
            if m' <> m then add m' m;
            pat m' c.pat;
            Option.iter (expr m') c.guard;
            expr m' c.body)
          cases
    | EVar _ | EInt _ | EBool _ | EUnit | ENone | ENil | EUnreachable -> ()
  in
  List.iter
    (fun (f : fn) ->
      let m = module_of_name f.name in
      Option.iter (expr m) f.spec;
      expr m f.body)
    p.fns;
  List.iter
    (fun (t : typing) ->
      let m = module_of_loc t.t_constr.c_loc in
      List.iter (expr m) t.t_sorts;
      Option.iter (expr m) t.t_when)
    (p.typing @ p.leaf_typing);
  module_refs :=
    List.map
      (fun m ->
        (m, List.filter_map (fun (a, d) -> if a = m then Some d else None) !refs))
      (List.sort_uniq compare (List.map fst !refs))

let generic_deps m =
  Option.value ~default:[] (List.assoc_opt m !module_uses)
  @ Option.value ~default:[] (List.assoc_opt m !module_refs)
  |> List.filter (fun d -> d <> m)
  |> List.sort_uniq compare
  |> List.map (fun d ->
      if not (is_generic_module d) then
        raise
          (Check.Error
             ( Location.none,
               Printf.sprintf
                 "module %s is proved once in Lean ([@@@lean_module]), but the \
                  module %s that it uses is not"
                 m d ));
      d)

(** The modules proved once that [m] uses, directly or not, each after those it
    uses, and [m] last. A module proved once cannot use itself, through others:
    its interface would be a part of itself. *)
let generic_order m =
  let rec go path acc d =
    if List.mem d path then
      let cycle = List.rev (d :: path) in
      let cycle =
        let rec from = function x :: l when x <> d -> from l | l -> l in
        from cycle
      in
      raise
        (Check.Error
           ( Location.none,
             Printf.sprintf
               "the modules proved once in Lean ([@@@lean_module]) use each \
                other: %s; prove them per language, or merge them"
               (String.concat " -> " cycle) ))
    else if List.mem d acc then acc
    else List.fold_left (go (d :: path)) acc (generic_deps d) @ [ d ]
  in
  go [] [] m

(** The modules proved once that [m] uses, directly or not, and [m]. *)
let generic_closure m = List.sort_uniq compare (generic_order m)

(** The modules proved once that [m] uses, directly or not, each after those it
    uses: the parameters of its interface. *)
let iface_deps m = List.filter (( <> ) m) (generic_order m)

(** The modules proved once that [m] uses and that no other of them uses: the
    parents of its [Ops]. *)
let direct_deps m =
  let deps = generic_deps m in
  List.filter
    (fun d ->
      not
        (List.exists
           (fun d' -> d' <> d && List.mem d (generic_closure d'))
           deps))
    (List.sort_uniq compare deps)

(** The modules proved once, in the order of their declaration. *)
let generic_modules () = List.map fst !lang.lean_modules

(** The modules proved once, each after those it uses. *)
let ordered_modules () =
  List.fold_left
    (fun acc m ->
      acc @ List.filter (fun d -> not (List.mem d acc)) (generic_order m))
    [] (generic_modules ())

let groot m = Option.get (module_root m)

(** The interfaces are unbundled: the interface [R.Syntax B L1 .. Ln] of a
    module has the fields of that module only, and takes as parameters the terms
    of the language ([B : Kanon.Base S]) and the interfaces of the modules it
    uses, directly or not ([iface_deps]), so that a module that two others use
    (a diamond) is one parameter, whose lemmas apply as they are. Likewise, its
    class [R.Sem L] takes the instances of theirs. *)

(** The interface of [m], over the terms [base] and the interfaces [var d] of
    the modules it uses. *)
let syntax_ty ?(base = "B") ?sem ~var m =
  String.concat " "
    (((groot m ^ ".Syntax")
     :: (match sem with Some s -> [ "(S := " ^ s ^ ")" ] | None -> []))
    @ (base :: List.map var (iface_deps m)))

(** The variable of the interface of [d] in the files of the module [self]. *)
let mvar self d = if d = self then "L" else "L" ^ d

(** The binders of the terms and of the interfaces of the modules that [m] uses,
    implicit (or [explicit]), in the files of [m]. *)
let iface_binders ?(explicit = false) m =
  let b x t =
    if explicit then "(" ^ x ^ " : " ^ t ^ ")" else "{" ^ x ^ " : " ^ t ^ "}"
  in
  String.concat " "
    (b "B" "Kanon.Base S"
    :: List.map
         (fun d -> b (mvar m d) (syntax_ty ~var:(mvar m) d))
         (iface_deps m))

(** The interface of the module [m] that a language gives ([Interface.lean]):
    [numSyntax] for [Num]; [modBase] for its terms. *)
let lsyntax m = with_sem_args (String.uncapitalize_ascii m ^ "Syntax")

(** The instances of the semantics of the modules that [m] uses. *)
let sem_insts m =
  String.concat ""
    (List.map
       (fun d -> Printf.sprintf "[%s.Sem %s] " (groot d) (mvar m d))
       (iface_deps m))

let ops_parent m = "to" ^ m ^ "Ops"
let sound_parent m = "to" ^ m ^ "Sound"

(** The field of [Ops.Sound] that is what the module [m] assumes of its oracles
    ([Oracle.Compat]). *)
let orc_field m = String.lowercase_ascii m ^ "_orc"

let in_module m (loc : Location.t) = module_of_loc loc = Some m

(** Whether the arm [a] of [f] is proved once, by the module of its case. *)
let generic_arm (f : fn) (a : arm) =
  f.cases
  && (not f.lean_closed)
  &&
  match module_of_loc a.a_case.cloc with
  | Some m ->
      is_generic_module m
      && is_generic_module (Option.get (module_of_name f.name))
  | None -> false

let arm_module (a : arm) = Option.get (module_of_loc a.a_case.cloc)

(** [set_option maxHeartbeats n in], before a generated proof of an arm of [f]
    (of a law, for [None]): its own bound, that of [f] ([[@lean_heartbeats n]]),
    or else that of the language ([[@@@lean_heartbeats n]]). *)
let heartbeats (f : fn option) ft =
  let n =
    match f with
    | Some { heartbeats = Some n; _ } -> n
    | _ -> !lang.lean_heartbeats
  in
  pf ft "set_option maxHeartbeats %d in@ " n

(** The proof that the operands of [op] commute, a lemma of [kanon_comm]: by the
    module that declares it if it is proved once, else by [kanon_proof%]. *)
let comm_proof ft ((op : constr), _) =
  let n = comm_name op in
  match module_of_loc op.c_loc with
  | Some m when is_generic_module m ->
      let xs = List.mapi (fun i _ -> Printf.sprintf "x%d" (i + 1)) op.c_args in
      pf ft
        "@[<v 2>@@[kanon_comm_lemma] theorem %s.ok : %s.Stmt :=@ fun%s %sa b t \
         => %s.%s.comm.ok (S := %s) %s %sa b t@]@ @ "
        n n (sem_args ())
        (String.concat "" (List.map (fun x -> x ^ " ") xs))
        (groot m) op.c_name (with_sem_args "sem") (lsyntax m)
        (String.concat "" (List.map (fun x -> x ^ " ") xs))
  | _ ->
      pf ft
        "%t@@[kanon_comm_lemma] theorem %s.ok : %s.Stmt := kanon_proof%% %s@ @ "
        (heartbeats None) n n n

(** The proofs of the rules of a [[@cases]] function from those of its arms, and
    of the arms derived by commutativity. *)
let cases_proofs ft (f : fn) =
  let hb = heartbeats (Some f) in
  List.iter
    (fun (r, arms) ->
      List.iteri
        (fun i a ->
          (* the operands of a swapped arm are other terms than those of the arm
             that it is derived from, which the assumptions are about *)
          let derived =
            if preconditions f = [] && not (generic_arm f a) then
              derived_from f arms a
            else None
          in
          match derived with
          | _ when generic_arm f a ->
              (* proved once, by its module *)
              let m = arm_module a in
              pf ft
                "%t@[<v 2>theorem %s.ok : %s.Stmt :=@ fun%s O hO => %s.%s.ok \
                 (S := %s) %s@ (Ops.to%s%s O) (Ops.Sound.to%s hO)@]@ @ "
                hb (arm_name f r arms i) (arm_name f r arms i) (sem_args ())
                (groot m) (arm_name f r arms i) (with_sem_args "sem")
                (lsyntax m) m (sem_args ()) m
          | None ->
              (* a hand-written [.proof] if there is one, else the default
                 tactic *)
              pf ft "%ttheorem %s.ok : %s.Stmt := kanon_proof%% %s@ @ " hb
                (arm_name f r arms i) (arm_name f r arms i)
                (arm_name f r arms i)
          | Some (b, args, top, nested, swapped) ->
              let j =
                let rec find k = function
                  | x :: _ when x == b -> k
                  | _ :: l -> find (k + 1) l
                  | [] -> assert false
                in
                find 0 arms
              in
              let hg = if a.a_case.guard = None then "" else " hg" in
              let term q =
                let t, _, _ = pat_term q in
                t
              in
              let comm o = Fmt.str "%s.ok%s .." (comm_name o) (sem_args ()) in
              pf ft "%t@[<v 2>theorem %s.ok : %s.Stmt := by@ intro%s O hO%a%s@ "
                hb (arm_name f r arms i) (arm_name f r arms i) (sem_args ())
                (fun ft -> List.iter (fun (x, _) -> pf ft " %s" x))
                a.a_binders hg;
              (* each swapped node of [a] refines that of [b], inner ones first:
                 by commutativity, and congruence for the swaps inside *)
              List.iter
                (fun ((qa : pat), qb, o) ->
                  let inner =
                    List.exists
                      (fun ((qa' : pat), _, _) ->
                        qa'.pid <> qa.pid && List.mem qa'.pid (pids qa))
                      nested
                  in
                  pf ft "@[<hv 2>have : Refines%s %s@ %s :=@ " (sem_args ())
                    (term qa) (term qb);
                  if inner then
                    pf ft "Refinement.trans (%s) (by kanon_congr)@]@ " (comm o)
                  else pf ft "%s@]@ " (comm o))
                nested;
              if swapped then
                (* the body of [b] is refined by that of [a], which swaps some
                   of its terms *)
                pf ft
                  "@[<hv 2>refine Refinement.trans ?_@ (Refinement.trans \
                   (%s.ok%s O hO%a%s)@ (by (try dsimp only); (repeat' apply \
                   Refinement.ite_congr) <;> first | exact Refinement.refl | \
                   kanon_comm))@]@ "
                  (arm_name f r arms j) (sem_args ())
                  (fun ft -> List.iter (pf ft " %s"))
                  args hg
              else
                pf ft
                  "@[<hv 2>refine Refinement.trans ?_@ (%s.ok%s O hO%a%s)@]@ "
                  (arm_name f r arms j) (sem_args ())
                  (fun ft -> List.iter (pf ft " %s"))
                  args hg;
              pf ft "simp only [%s.spec%s]@ " (qn f.name)
                (if List.mem "type_of" (calls (Option.get f.spec)) then
                   ", ty, Term.ty_mk"
                 else "");
              Option.iter
                (fun o -> pf ft "refine Refinement.trans (%s) ?_@ " (comm o))
                top;
              pf ft "kanon_congr@]@ @ ")
        arms;
      (* the alternatives come out of [repeat' rcases] in order *)
      pf ft
        "@[<v 2>theorem %s.r_%s.proof : %s.r_%s.Stmt := by@ intro%s O hO %a \
         res%a h@ simp only [%s.r_%s] at h@ repeat' rcases orElse_some h with \
         h | h@ %a@]@ @ "
        (qn f.name) (id r) (qn f.name) (id r) (sem_args ()) args f pre_names f
        (qn f.name) (id r)
        (Format.pp_print_list
           ~pp_sep:(fun ft () -> pf ft "@ ")
           (fun ft i ->
             pf ft "· kanon_arm h (%s.ok%s O hO)" (arm_name f r arms i)
               (sem_args ())))
        (List.init (List.length arms) Fun.id))
    (arms f)

(** Whether some arms of [f] are proved once, by their modules. *)
let has_generic_arms (f : fn) =
  List.exists (fun (_, arms) -> List.exists (generic_arm f) arms) (arms f)

(** The modules that prove arms of [f]. *)
let generic_arm_modules (f : fn) =
  List.concat_map
    (fun (_, arms) ->
      List.filter_map
        (fun a -> if generic_arm f a then Some (arm_module a) else None)
        arms)
    (arms f)
  |> List.sort_uniq compare

(** Whether the commutativity of [op] is proved once, by its module. *)
let generic_comm ((op : constr), _) =
  match module_of_loc op.c_loc with
  | Some m -> is_generic_module m
  | None -> false

(** Whether some generated proof is by the tactics of the language
    ([kanon_proof%], which [Lib/Rule.lean] gives [kanon_auto]): that of an arm
    that is not proved once by its module, of a postcondition, or of the
    commutativity of an operator that is not. *)
let uses_tactics ctx =
  List.exists
    (fun f ->
      postcondition f <> None
      || (f.cases
         && List.exists
              (fun (_, arms) ->
                List.exists (fun a -> not (generic_arm f a)) arms)
              (arms f)))
    (rule_fns ctx)
  || List.exists (fun op -> not (generic_comm op)) (comm_ops ())

(** The hand-written proofs of the generated proofs at [path] (under
    [Soundness]): the file at the same path under [Proofs], if it exists. *)
let proof_imports ~has_proof path =
  let p = "Proofs" :: List.tl path in
  if has_proof (root ()) p then [ mdp p ] else []

(** [Soundness/Laws.lean]: the commutativity of the operators, which the proofs
    of the arms use. *)
let laws_file ~sources ~has_proof ctx =
  let path = [ "Soundness"; "Laws" ] in
  let generic =
    List.sort_uniq compare
      (List.filter_map
         (fun ((op : constr), _) ->
           match module_of_loc op.c_loc with
           | Some m when is_generic_module m -> Some m
           | _ -> None)
         (comm_ops ()))
  in
  lean_file ~sources path
    ((md "Statements"
     ::
     (if uses_tactics ctx then [ md "Lifts"; md "Nodes"; md "Lib.Rule" ] else [])
     )
    @ (if generic <> [] then
         md "Instance"
         :: List.map (fun m -> groot m ^ ".Soundness.Laws") generic
       else [])
    @ proof_imports ~has_proof path)
    (fun ft -> List.iter (comm_proof ft) (comm_ops ()))

(** [Soundness/M/f.lean]: the proofs of the arms of a rule function, of its
    rules, of its postcondition, and that its step refines its spec. *)
let fn_soundness_file ~sources ~has_proof ctx (f : fn) =
  let path = fn_path "Soundness" f.name in
  let generic = generic_arm_modules f in
  lean_file ~sources path
    ([ mdp (fn_path "Statements" f.name); md "Soundness.Laws" ]
    @ (if generic <> [] then
         md "Instance"
         :: List.map
              (fun m -> groot m ^ "." ^ String.concat "." (List.map id path))
              generic
       else [])
    @ proof_imports ~has_proof path)
    (fun ft ->
      if f.cases then cases_proofs ft f;
      if postcondition f <> None then
        pf ft
          "%ttheorem %s.post.main.ok : %s.post.main.Stmt := kanon_proof%% \
           %s.post.main@ @ "
          (heartbeats (Some f)) (qn f.name) (qn f.name) (qn f.name);
      pf ft
        "@[<v 2>theorem %s.step_sound %s(O : Ops) (hO : O.Sound%s) %a%a :@ \
         Refines%s (%s.spec %a) (%s.step O %a) := by@ unfold %s.step@ "
        (qn f.name) (sem_binders ()) (sem_args ()) params f
        (pre_binders ?rename:None) f (sem_args ()) (qn f.name) args f
        (qn f.name) args f (qn f.name);
      List.iter
        (fun r ->
          let _, _, g = r in
          let n = id (rule_name f g) in
          pf ft
            "refine Refinement.firstSome_cons (fun res h => %s.r_%s.proof%s O \
             hO %a res%a h) ?_@ "
            (qn f.name) n (sem_args ()) args f pre_names f)
        (rules f);
      pf ft "exact Refinement.firstSome_nil@]@ @ ")

(** [Soundness.lean]: every rule function refines its spec, for any fuel. *)
let soundness_file ~sources ctx =
  lean_file ~sources [ "Soundness" ]
    (md "Model"
    :: md "Soundness.Laws"
    :: List.map (fun f -> mdp (fn_path "Soundness" f.name)) (rule_fns ctx))
    (fun ft ->
      pf ft
        "/-- Every rule function refines its spec, for any amount of fuel. -/@ \
         @[<v 2>theorem opsN_sound %s(orc : Oracle) (h : orc.Compat%s) :@ ∀ n, \
         (opsN orc n).Sound%s@ | 0 =>\n\
        \    { orc := h"
        (sem_binders ()) (sem_args ()) (sem_args ());
      List.iter
        (fun f ->
          pf ft ",\n      %s := fun %a%a => Refinement.refl" (fld f.name) args f
            pre_names f)
        (rule_fns ctx);
      pf ft
        " }\n\
        \  | n + 1 =>\n\
        \    have hO := opsN_sound%s orc h n\n\
        \    { orc := hO.orc"
        (sem_args ());
      List.iter
        (fun f ->
          pf ft ",\n      %s := %s.step_sound%s _ hO" (fld f.name) (qn f.name)
            (sem_args ()))
        (rule_fns ctx);
      pf ft " }@]@ @ ")

