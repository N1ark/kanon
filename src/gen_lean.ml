(* [Nodes.lean]: the typing and the evaluation of each node *)

(** The nodes, as their name ([Kind.Int], [Op2.Plus]), the binders of their
    arguments and operands, and their kind over these. *)
let nodes () =
  let fresh x =
    if List.mem_assoc x !lang.lean_params then "kanon__" ^ x else x
  in
  let xs args =
    List.mapi
      (fun i a -> (fresh (Printf.sprintf "x%d" (i + 1)), ty_str (arg_ty a)))
      args
  in
  let apply c = function
    | [] -> c
    | l -> Printf.sprintf "(%s %s)" c (String.concat " " (List.map fst l))
  in
  List.filter_map
    (fun (c : constr) ->
      if c.c_res = TKind && not (List.mem c.c_name !lang.node_kinds) then
        let args = xs c.c_args in
        Some (lean_constr c, args, apply (lean_constr c) args)
      else
        match Check.node_of_op c with
        | Some (kc, operands) ->
            let args = xs c.c_args in
            let operands =
              List.mapi
                (fun i t -> (fresh (Printf.sprintf "a%d" (i + 1)), ty_str t))
                operands
            in
            Some
              ( lean_constr c,
                args @ operands,
                Printf.sprintf "(%s %s %s)" (lean_constr kc)
                  (apply (lean_constr c) args)
                  (String.concat " " (List.map fst operands)) )
        | None -> None)
    !lang.constrs

(** [Nodes.lean]: for each node [C], its typing [Nodes.C.wt] and its evaluation
    [Nodes.C.ev] in terms of those of its operands, in the simp sets
    [kanon_node_wt] and [kanon_node_ev] of the proofs of the arms: the
    definitions of the semantics, unfolded at the node by [kanon_node_lemma] of
    Kanon's library. *)
let nodes_file ~sources =
  let fresh x =
    if List.mem_assoc x !lang.lean_params then "kanon__" ^ x else x
  in
  let t = fresh "t" and rho = fresh "ρ" and sem = with_sem_args "sem" in
  lean_file ~sources [ "Nodes" ]
    [ "KanonCore.Node"; md "Semantics" ]
    (fun ft ->
      List.iter
        (fun (name, binders, kind) ->
          let binders =
            String.concat ""
              (List.map
                 (fun (x, ty) -> Printf.sprintf "(%s : %s) " x ty)
                 binders)
          in
          let term = Printf.sprintf "(Term.mk %s %s)" kind t in
          pf ft
            "@[<v 2>kanon_node_lemma kanon_node_wt Nodes.%s.wt %s%s(%s : %a) \
             :@ %s.WT %s@]@ @ "
            name (sem_binders ()) binders t lean_ty TSty sem term;
          pf ft
            "@[<v 2>kanon_node_lemma kanon_node_ev Nodes.%s.ev %s(%s : %s.Env) \
             %s(%s : %a) :@ %s.ev %s %s@]@ @ "
            name (sem_binders ()) rho sem binders t lean_ty TSty sem rho term)
        (nodes ()))

