(* Files *)

(** The root of the files being generated, when they are those of a module
    proved once rather than those of the language. *)
let cur_root : string option ref = ref None

(** The Lean namespace of the model, and the root of its modules (or those of
    the module whose files are generated). *)
let root () = match !cur_root with Some r -> r | None -> !lang.lean_root

(** [k ()], generating the files of the root [r]. *)
let with_root r k =
  let saved = !cur_root in
  cur_root := Some r;
  Fun.protect ~finally:(fun () -> cur_root := saved) k

(** The module [m] of the model. *)
let md m = root () ^ "." ^ m

(** A generated Lean file: the path of its module under the root
    ([["Model"; "Bool"; "and_"]] for [R.Model.Bool.and_]), and its contents. *)
type file = {
  froot : string;  (** the root of the module, [R] *)
  path : string list;
  contents : Format.formatter -> unit;
}

(** The name of the module at [path] under the root. *)
let mdp path = String.concat "." (root () :: List.map id path)

(** The path of the file of the function [name] in the directory [dir]: in the
    directory of its module, [[dir; "Bitvec"; "add"]] for [Bitvec.add], or in
    [dir] itself for a function that Kanon provides. *)
let fn_path dir name =
  dir
  :: (match split_name name with Some (m, x) -> [ m; x ] | None -> [ name ])

(** The parameters of the semantics, as binders, implicit binders, and
    arguments. *)
let sem_binders () =
  String.concat ""
    (List.map (fun (x, t) -> Printf.sprintf "(%s : %s) " x t) !lang.lean_params)

let sem_implicits () =
  String.concat ""
    (List.map (fun (x, t) -> Printf.sprintf "{%s : %s} " x t) !lang.lean_params)

let sem_args () =
  String.concat "" (List.map (fun (x, _) -> " " ^ x) !lang.lean_params)

let header ~sources ft imports =
  pf ft "@[<v>-- Generated by kanon from %a. Do not edit.@ "
    (list Format.pp_print_string)
    sources;
  List.iter (fun i -> pf ft "import %s@ " i) imports;
  pf ft
    "@ set_option linter.unusedVariables false@ set_option maxHeartbeats \
     1000000@ @ noncomputable section@ @ namespace %s@ @ open Classical Kanon@ \
     @ "
    (root ())

(** The file at [path] that imports [imports] and has [body] in the namespace of
    the model. *)
let lean_file ~sources path imports body =
  let r = root () in
  {
    froot = r;
    path;
    contents =
      (fun ft ->
        with_root r (fun () ->
            header ~sources ft imports;
            body ft;
            pf ft "end %s@]@." r));
  }

(** The parameter a recursive helper recurses on: the first variable its body
    matches on. *)
let rec decreasing (f : fn) (e : expr) =
  match e.e with
  | ELet (_, _, b) | EAssert (_, b) | ELetFun (_, _, _, b) -> decreasing f b
  | EMatch (scruts, _) ->
      List.find_map
        (fun (s : expr) ->
          match s.e with
          | EVar x when List.mem_assoc x f.params -> Some x
          | _ -> None)
        scruts
  | _ -> None

let fn_def ctx ft (f : fn) ~o ~kw ~recursive =
  pf ft "%a@[<v 2>%s %s%s %a : %a :=@ %a@]@ " doc f.fdoc kw (qn f.name)
    (if o then " (O : Ops)" else "")
    params f lean_ty f.ret (expr ctx) f.body;
  (if recursive then
     match decreasing f f.body with
     | Some x ->
         pf ft
           "termination_by sizeOf %s@ decreasing_by all_goals (simp_wf; \
            omega)@ "
           (id x)
     | None -> ());
  pf ft "@ "

let rule_fns ctx = List.filter (fun f -> fn_kind ctx f.name = Rule) ctx.fns

(** The helpers, in groups of mutually recursive ones, callees first: each group
    is defined in a file of its own, named after its first function. *)
let helper_groups ctx =
  Gen_ocaml.sccs (List.filter (fun f -> fn_kind ctx f.name <> Rule) ctx.fns)

(** The path of the file of the group of the helper [name]. *)
let helper_path ctx name =
  match
    List.find_opt
      (List.exists (fun (g : fn) -> g.name = name))
      (helper_groups ctx)
  with
  | Some (g :: _) -> fn_path "Model" g.name
  | _ -> invalid_arg ("gen_lean: not a helper: " ^ name)

(** The modules of the helpers that [e] calls. *)
let helper_imports ctx (e : expr) =
  Gen_ocaml.calls [] e
  |> List.filter (fun g ->
      match List.assoc_opt g ctx.kinds with
      | Some (Pure | OHelper) -> true
      | _ -> false)
  |> List.map (helper_path ctx)
  |> List.sort_uniq compare

let group_def ctx ft group =
  let o = fn_kind ctx (List.hd group).name = OHelper in
  match group with
  | [ f ] when not (Gen_ocaml.is_recursive [ f ]) ->
      fn_def ctx ft f ~o ~kw:"def" ~recursive:false
  | _ ->
      pf ft "mutual@ @ ";
      List.iter (fn_def ctx ft ~o ~kw:"def" ~recursive:true) group;
      pf ft "end@ @ "

(** [Ops.lean]: the oracles, the record [Ops] of the rule functions, their specs
    and [opsRaw]. *)
let ops_file ~sources ctx =
  let spec_imports =
    List.concat_map
      (fun f -> helper_imports ctx (Option.get f.spec))
      (rule_fns ctx)
    |> List.sort_uniq compare
  in
  lean_file ~sources [ "Ops" ] (md "Signatures" :: List.map mdp spec_imports)
    (fun ft ->
      pf ft
        "/-- The primitives that the model is parameterised by. -/@ @[<v \
         2>structure Oracle where";
      List.iter
        (fun (q : prim) ->
          if q.oracle then (
            pf ft "@ %a%s : " doc q.pdoc (plain_name q.pname);
            List.iter (fun t -> pf ft "%a → " lean_ty t) q.pargs;
            lean_ty ft q.pret))
        ctx.prims;
      pf ft "@]@ @ ";
      pf ft
        "/-- The rule functions, as used by the rules. -/@ @[<v 2>structure \
         Ops where@ orc : Oracle";
      List.iter
        (fun f -> pf ft "@ %a%s : %a" doc f.fdoc (fld f.name) arrow f)
        (rule_fns ctx);
      pf ft "@]@ @ ";
      List.iter
        (fun f ->
          pf ft "%a@[<v 2>def %s.spec %a : Term :=@ %a@]@ @ " doc f.fdoc
            (qn f.name) params f (expr ctx) (Option.get f.spec))
        (rule_fns ctx);
      pf ft "@[<v 2>def opsRaw (orc : Oracle) : Ops :=@ { orc := orc%a }@]@ @ "
        (fun ft () ->
          List.iter
            (fun f ->
              pf ft ",\n    %s := fun %a => %s.spec %a" (fld f.name) args f
                (qn f.name) args f)
            (rule_fns ctx))
        ())

(** [Model/M/h.lean]: a group of helpers. *)
let helper_file ~sources ctx group =
  let f = List.hd group in
  let base =
    if fn_kind ctx f.name = OHelper then md "Ops" else md "Signatures"
  in
  let own = fn_path "Model" f.name in
  let imports =
    List.concat_map (fun (g : fn) -> helper_imports ctx g.body) group
    |> List.sort_uniq compare
    |> List.filter (fun p -> p <> own)
  in
  lean_file ~sources own (base :: List.map mdp imports) (fun ft ->
      group_def ctx ft group)

(** [Model/M/f.lean]: the rules of a rule function and its step. *)
let rule_file ~sources ctx (f : fn) =
  lean_file ~sources (fn_path "Model" f.name)
    (md "Ops" :: List.map mdp (helper_imports ctx f.body))
    (fun ft ->
      let rs = rules f in
      List.iter (rule_def ctx ft f) rs;
      pf ft
        "@[<v 2>def %s.step (O : Ops) %a : Term :=@ (firstSome [%a]).getD \
         (%s.spec %a)@]@ @ "
        (qn f.name) params f
        (list (fun ft r ->
             pf ft "%s.r_%s O %a" (qn f.name)
               (id
                  (rule_name f
                     (let _, _, g = r in
                      g)))
               args f))
        rs (qn f.name) args f)

(** [Model.lean]: the rule functions, with [n] steps of fuel. *)
let model_file ~sources ctx =
  lean_file ~sources [ "Model" ]
    (List.map (fun f -> mdp (fn_path "Model" f.name)) (rule_fns ctx))
    (fun ft ->
      pf ft "@[<v 2>def opsStep (O : Ops) : Ops :=@ { orc := O.orc%a }@]@ @ "
        (fun ft () ->
          List.iter
            (fun f -> pf ft ",\n    %s := %s.step O" (fld f.name) (qn f.name))
            (rule_fns ctx))
        ();
      pf ft
        "@[<v 2>def opsN (orc : Oracle) : Nat → Ops@ | 0 => opsRaw orc@ | n + \
         1 => opsStep (opsN orc n)@]@ @ ")

(** The files of the model: [Ops.lean], one file per group of helpers and per
    rule function, and [Model.lean]. *)
let model_files ~sources ctx =
  (ops_file ~sources ctx
  :: List.map (helper_file ~sources ctx) (helper_groups ctx))
  @ List.map (rule_file ~sources ctx) (rule_fns ctx)
  @ [ model_file ~sources ctx ]

