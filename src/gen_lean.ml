(* Patterns *)

let rec pat ft (p : pat) =
  match p.p with
  | PAny -> pf ft "_"
  | PVar x -> pf ft "%s" (id x)
  | PAs (q, x) -> pf ft "%s@%a" (id x) pat q
  | POr _ | PComm _ -> failwith "gen_lean: or-pattern after desugaring"
  | PInt z -> pf ft "(%s : Int)" (Z.to_string z)
  | PBool b -> pf ft "%b" b
  | PUnit -> pf ft "()"
  | PTuple l -> pf ft "(%a)" (list pat) l
  | PSome q -> pf ft "(some %a)" pat q
  | PNone -> pf ft "none"
  | PNil -> pf ft "[]"
  | PCons (h, t) -> pf ft "(%a :: %a)" pat h pat t
  | PRecord fs ->
      let field (f, _) =
        match List.assoc_opt f fs with
        | Some p -> Fmt.str "%a" pat p
        | None -> "_"
      in
      pf ft "⟨%s⟩"
        (String.concat ", " (List.map field (decl_of_ty p.pty).d_fields))
  | PConstr (c, _) when !generic <> None && not (is_data c) ->
      unsupported p.ploc "the pattern of %s" c.c_name
  | PConstr (c, args) ->
      let inner ft () =
        match args with
        | [] -> pf ft "%s" (lean_constr c)
        | _ -> pf ft "(%s %a)" (lean_constr c) (list ~sep:" " pat) args
      in
      if p.pty = TTerm then pf ft "(Term.mk %a _)" inner () else inner ft ()

(* ---------------------------------------------------------------- *)
(* Expressions *)

(** Variables printed as given terms: the scrutinees and [as] binders of a
    [[@cases]] alternative, in its statement. *)
let subst : (string * string) list ref = ref []

(** [k ()] with the variables [xs] bound, hence not substituted. *)
let binding xs k =
  let saved = !subst in
  subst := List.filter (fun (x, _) -> not (List.mem x xs)) saved;
  Fun.protect ~finally:(fun () -> subst := saved) k

(** Whether the rule being printed belongs to a [[@cases]] function. *)
let cases_style = ref false

let rec expr ctx ft (e : expr) =
  let expr = expr ctx in
  match e.e with
  | EVar x -> (
      match List.assoc_opt x !subst with
      | Some t -> pf ft "%s" t
      | None -> pf ft "%s" (id x))
  | EInt z -> pf ft "(%s : Int)" (Z.to_string z)
  | EBool b -> pf ft "%b" b
  | EUnit -> pf ft "()"
  | EUnreachable -> pf ft "default"
  | EConstr (c, args) when !generic <> None -> gconstr ctx ft e.eloc c args
  | ENode (k, t) when !generic <> None ->
      pf ft "(%s %a %a)" (gfield_of None "node") expr k expr t
  | ECall ("type_of", [ a ]) when !generic <> None -> pf ft "(S.ty %a)" expr a
  | ECall ("mk_commut_binop", [ { e = EConstr (o, oargs); _ }; l; r ])
    when !generic <> None ->
      let k a b ft () =
        pf ft "(%s %a)"
          (cfield o (kind_field o.c_name))
          (list ~sep:" " expr)
          (oargs @ [ a; b ])
      in
      pf ft "@[<hv>(if O.tag_le %a %a@ then %a@ else %a)@]" expr l expr r
        (k l r) () (k r l) ()
  | ECall (f, args) when !generic <> None ->
      let f =
        if is_oracle ctx f then "O." ^ fld f
        else if is_prim ctx f then nfield f (fld f)
        else
          match fn_kind ctx f with
          | Rule | OHelper -> "O." ^ fld f
          | Pure -> nfield f (fld f)
      in
      if args = [] then pf ft "%s" f
      else pf ft "(%s %a)" f (list ~sep:" " expr) args
  | EMatch _ when !generic <> None && e.ety = TSty ->
      unsupported e.eloc "a match on sorts"
  | EMatch (scruts, cases) when !generic <> None -> gmatch ctx ft (scruts, cases)
  | ELet (p, _, _) when !generic <> None && has_node_pat p ->
      unsupported e.eloc "a let that matches a node"
  | EConstr (c, []) -> pf ft "%s" (lean_constr c)
  | EConstr (c, args) ->
      pf ft "(%s %a)" (lean_constr c) (list ~sep:" " expr) args
  | ENode (k, t) -> pf ft "(Term.mk %a %a)" expr k expr t
  | ECall ("type_of", [ a ]) -> pf ft "(ty %a)" expr a
  | EArray l -> pf ft "#[%a]" (list expr) l
  | ECall ("array_length", [ a ]) -> pf ft "(arrayLength %a)" expr a
  | ECall ("array_get", [ a; i ]) -> pf ft "(arrayGet %a %a)" expr a expr i
  | ECall ("array_set", [ a; i; v ]) ->
      pf ft "(arraySet %a %a %a)" expr a expr i expr v
  | ECall ("array_of_list", [ l ]) -> pf ft "(List.toArray %a)" expr l
  | ECall ("array_to_list", [ a ]) -> pf ft "(Array.toList %a)" expr a
  | ECall (f, args) ->
      let f =
        if is_oracle ctx f then "O.orc." ^ plain_name f
        else if is_prim ctx f then plain_name f
        else
          match fn_kind ctx f with
          | Rule -> "O." ^ fld f
          | OHelper -> qn f ^ " O"
          | Pure -> qn f
      in
      if args = [] then pf ft "%s" f
      else pf ft "(%s %a)" f (list ~sep:" " expr) args
  | ELocalCall (f, args) -> pf ft "(%s %a)" (id f) (list ~sep:" " expr) args
  | EUnop (Neg, a) -> pf ft "(- %a)" expr a
  | EUnop (Not, a) -> pf ft "(! %a)" expr a
  | EBinop (op, a, b) -> (
      let infix s = pf ft "(%a %s %a)" expr a s expr b in
      let dec s = pf ft "(decide (%a %s %a))" expr a s expr b in
      match op with
      | Add -> infix "+"
      | Sub -> infix "-"
      | Mul -> infix "*"
      | Lt -> dec "<"
      | Le -> dec "≤"
      | Gt -> dec ">"
      | Ge -> dec "≥"
      | Eq -> dec "="
      | Ne -> dec "≠"
      | And -> infix "&&"
      | Or -> infix "||")
  | EIf (c, a, b) ->
      pf ft "@[<hv>(if %a@ then %a@ else %a)@]" expr c expr a expr b
  | ELet ({ p = PVar x; _ }, rhs, body) ->
      pf ft "@[<v>(let %s := %a;@ %a)@]" (id x) expr rhs
        (fun ft () -> binding [ x ] (fun () -> expr ft body))
        ()
  | ELet (p, rhs, body) ->
      pf ft "@[<v>(match %a with@ | %a =>@;<1 2>%a)@]" expr rhs pat p
        (fun ft () -> binding (pat_names p) (fun () -> expr ft body))
        ()
  | ELetFun (f, params, fbody, body) ->
      pf ft "@[<v>(let %s := fun %a =>@;<1 2>%a;@ %a)@]" (id f)
        (list ~sep:" " (fun ft (x, t) -> pf ft "(%s : %a)" (id x) lean_ty t))
        params
        (fun ft () ->
          binding (f :: List.map fst params) (fun () -> expr ft fbody))
        ()
        (fun ft () -> binding [ f ] (fun () -> expr ft body))
        ()
  | EMatch (scruts, cases)
    when e.ety = TSty || (List.rev cases |> List.hd).body.e = EUnreachable ->
      sort_match ctx ft (scruts, cases)
  | EMatch (scruts, cases) -> match_ ctx ft (scruts, cases)
  | ETuple l -> pf ft "(%a)" (list expr) l
  | ESome e -> pf ft "(some %a)" expr e
  | ENone -> pf ft "none"
  | ENil -> pf ft "[]"
  | ECons (h, t) -> pf ft "(%a :: %a)" expr h expr t
  | ERecord fs ->
      let d = decl_of_ty e.ety in
      pf ft "({ %a } : %a)"
        (list (fun ft (f, _) -> pf ft "%s := %a" f expr (List.assoc f fs)))
        d.d_fields lean_ty e.ety
  | EField (e, f) -> pf ft "%a.%s" expr e f
  | EAssert (_, body) -> expr ft body

and pat_names p = List.map fst (Check.binders p)

(** Whether [p] matches a node, or a sort. *)
and has_node_pat (p : pat) =
  match p.p with
  | PConstr (_, _) when p.pty = TTerm || p.pty = TSty -> true
  | PConstr (_, l) | PTuple l -> List.exists has_node_pat l
  | PAs (q, _) | PSome q -> has_node_pat q
  | PCons (h, t) -> has_node_pat h || has_node_pat t
  | PRecord fs -> List.exists (fun (_, q) -> has_node_pat q) fs
  | POr (a, b) | PComm (a, b) -> has_node_pat a || has_node_pat b
  | _ -> false

(** A constructor applied to [args], over the interface: a sort, or the kind of
    a node ([Op2 (Plus, a, b)] is [PlusK a b]). *)
and gconstr ctx ft loc (c : constr) args =
  let app name args =
    if args = [] then pf ft "%s" name
    else pf ft "(%s %a)" name (list ~sep:" " (expr ctx)) args
  in
  if c.c_res = TSty then app (cfield c c.c_name) args
  else if c.c_res = TKind && List.mem c.c_name !lang.node_kinds then
    match args with
    | { e = EConstr (o, oargs); _ } :: operands ->
        app (cfield o (kind_field o.c_name)) (oargs @ operands)
    | _ -> unsupported loc "an operator that is not a constructor"
  else if c.c_res = TKind then app (cfield c (kind_field c.c_name)) args
  else if is_data c then app (lean_constr c) args
  else unsupported loc "the constructor %s" c.c_name

(** A node pattern [p] (of a term): its node, and the patterns of its arguments
    and operands; or a pattern of a sort, and those of its arguments. *)
and node_pat (p : pat) =
  match p.p with
  | PConstr (k, args) when p.pty = TTerm ->
      let node, args =
        if List.mem k.c_name !lang.node_kinds then
          match args with
          | { p = PConstr (o, oargs); _ } :: operands -> (o, oargs @ operands)
          | _ ->
              unsupported p.ploc "an operator pattern that is not a constructor"
        else (k, args)
      in
      Some (node, args)
  | PConstr (k, args) when k.c_res = TSty -> Some (k, args)
  | _ -> None

(** A match over the interface: each case is a match of its own (see [match_]),
    in which the scrutinees that a case matches with a node (or a sort) are
    replaced by the matcher of that node ([asC v], an option of its arguments).
    The nodes inside those are matched by nested matches, on the variables that
    the outer ones bind to them ([kanon__n1], …). *)
and gmatch ctx ft (scruts, (cases : case list)) =
  let pats_of (c : case) =
    match (scruts, c.pat.p) with
    | [ _ ], _ -> [ c.pat ]
    | _, PTuple l -> l
    | _, PAny -> List.map (fun _ -> c.pat) scruts
    | _ -> unsupported c.cloc "a match on a tuple"
  in
  let tuple l =
    match l with
    | [] -> "()"
    | [ x ] -> x
    | _ -> "(" ^ String.concat ", " l ^ ")"
  in
  let str pp x = Fmt.str "%a" pp x in
  (* the patterns of a case, as layers of nested matches: each a list of
     discriminants, with their patterns, and whether these may fail *)
  let translate (c : case) =
    let n = ref 0 in
    let fresh () =
      incr n;
      Printf.sprintf "kanon__n%d" !n
    in
    (* [q] as a Lean pattern, its nodes bound to variables: and the matches of
       these variables *)
    let rec flat (q : pat) =
      match (q.p, node_pat q) with
      | _, Some _ ->
          let x = fresh () in
          (x, [ (x, q) ])
      | PAs (q', x), _ when Option.is_some (node_pat q') ->
          (id x, [ (id x, q') ])
      | _ when not (has_node_pat q) -> (str pat q, [])
      | PAs (q', x), _ ->
          let p', l = flat q' in
          (Printf.sprintf "%s@%s" (id x) p', l)
      | PTuple qs, _ ->
          let ps, ls = List.split (List.map flat qs) in
          ("(" ^ String.concat ", " ps ^ ")", List.concat ls)
      | PSome q', _ ->
          let p', l = flat q' in
          ("(some " ^ p' ^ ")", l)
      | PCons (h, t), _ ->
          let ph, lh = flat h and pt, lt = flat t in
          (Printf.sprintf "(%s :: %s)" ph pt, lh @ lt)
      | PConstr (k, qs), _ ->
          let ps, ls = List.split (List.map flat qs) in
          ( Printf.sprintf "(%s)" (String.concat " " (lean_constr k :: ps)),
            List.concat ls )
      | _ -> unsupported q.ploc "a pattern of nodes inside a value"
    in
    (* the match of a node (or a sort) [q] of the term [d], and what it leaves
       to match *)
    let matcher d (q : pat) =
      let k, args = Option.get (node_pat q) in
      let ps, ls = List.split (List.map flat args) in
      ( ( Printf.sprintf "(%s %s)" (cfield k ("as" ^ k.c_name)) d,
          "some " ^ tuple ps,
          true ),
        List.concat ls )
    in
    let rec layers pending =
      match pending with
      | [] -> []
      | _ ->
          let ms = List.map (fun (d, q) -> matcher d q) pending in
          List.map fst ms :: layers (List.concat_map snd ms)
    in
    let first, pending =
      List.split
        (List.map2
           (fun (sc : expr) (q : pat) ->
             let s = str (expr ctx) sc in
             match (q.p, node_pat q) with
             | _, Some _ ->
                 let m, l = matcher s q in
                 ([ m ], l)
             | PAs (q', x), _ when Option.is_some (node_pat q') ->
                 let m, l = matcher s q' in
                 ([ m; (s, id x, false) ], l)
             | _ ->
                 let p, l = flat q in
                 ([ (s, p, not (irrefutable_flat q)) ], l))
           scruts (pats_of c))
    in
    List.concat first :: layers (List.concat pending)
  in
  (* the nested matches of [ls], then [rhs] *)
  let rec nest ft (ls, rhs) =
    match ls with
    | [] -> rhs ft ()
    | l :: rest ->
        let d = String.concat ", " (List.map (fun (d, _, _) -> d) l) in
        let p = String.concat ", " (List.map (fun (_, p, _) -> p) l) in
        let wild = String.concat ", " (List.map (fun _ -> "_") l) in
        if List.exists (fun (_, _, r) -> r) l then
          pf ft "@[<hv 2>(match %s with@ | %s =>@ %a@ | %s => none)@]" d p nest
            (rest, rhs) wild
        else pf ft "@[<hv 2>(match %s with@ | %s =>@ %a)@]" d p nest (rest, rhs)
  in
  let alt ft (c : case) = nest ft (translate c, guarded ctx c) in
  let alts, default =
    match List.rev cases with
    | ({ guard = None; _ } as c) :: rest when irrefutable c.pat ->
        ( List.rev rest,
          fun ft () ->
            match translate c with
            | [ ds ] ->
                pf ft "@[<hv 2>(match %s with@ | %s =>@ %a)@]"
                  (String.concat ", " (List.map (fun (d, _, _) -> d) ds))
                  (String.concat ", " (List.map (fun (_, p, _) -> p) ds))
                  (fun ft () ->
                    binding (pat_names c.pat) (fun () -> expr ctx ft c.body))
                  ()
            | _ -> assert false )
    | _ -> (cases, fun ft () -> pf ft "Inhabited.default")
  in
  match alts with
  | [] -> default ft ()
  | _ ->
      pf ft "@[<hv 2>((firstSome [%a]).getD@ %a)@]"
        (Format.pp_print_list ~pp_sep:(fun ft () -> pf ft ",@ ") alt)
        alts default ()

(** A case's result: [some body], under its guard. *)
and guarded ctx (c : case) ft () =
  binding (pat_names c.pat) (fun () ->
      match c.guard with
      | None when !cases_style ->
          pf ft "@[<hv>(whenSome true@ (%a))@]" (expr ctx) c.body
      | None -> pf ft "some (%a)" (expr ctx) c.body
      | Some g when !cases_style ->
          pf ft "@[<hv>(whenSome %a@ (%a))@]" (expr ctx) g (expr ctx) c.body
      | Some g ->
          pf ft "@[<hv>(if %a@ then some (%a)@ else none)@]" (expr ctx) g
            (expr ctx) c.body)

(** Whether a pattern matches every value of its type, once its nodes are
    variables (see [gmatch]). *)
and irrefutable_flat (p : pat) =
  Option.is_some (node_pat p)
  ||
  match p.p with
  | PAny | PVar _ | PUnit -> true
  | PAs (q, _) -> irrefutable_flat q
  | PTuple l -> List.for_all irrefutable_flat l
  | PRecord fs -> List.for_all (fun (_, q) -> irrefutable_flat q) fs
  | _ -> false

(** Whether a pattern matches every value of its type. *)
and irrefutable (p : pat) =
  match p.p with
  | PAny | PVar _ | PUnit -> true
  | PAs (q, _) -> irrefutable q
  | PTuple l -> List.for_all irrefutable l
  | PRecord fs -> List.for_all (fun (_, q) -> irrefutable q) fs
  | _ -> false

(** How a match on [scruts] is printed: on several discriminants when possible
    (so that Lean sees the recursion on each of them), else on a tuple. *)
and discriminants ctx (scruts, (cases : case list)) =
  let multi =
    List.length scruts > 1
    && List.for_all
         (fun (c : case) ->
           match c.pat.p with PTuple _ | PAny -> true | _ -> false)
         cases
  in
  let d ft () =
    if multi || List.length scruts = 1 then list (expr ctx) ft scruts
    else pf ft "(%a)" (list (expr ctx)) scruts
  in
  let p ft (q : pat) =
    match q.p with
    | PTuple l when multi -> list pat ft l
    | PAny when multi -> list (fun ft _ -> pf ft "_") ft scruts
    | _ -> pat ft q
  in
  let wild ft () =
    if multi then list (fun ft _ -> pf ft "_") ft scruts else pf ft "_"
  in
  (d, p, wild)

(** A match on sorts, which Kanon builds to infer the sort of a node and whose
    cases have no guard: a plain Lean match. *)
and sort_match ctx ft (scruts, cases) =
  let d, p, _ = discriminants ctx (scruts, cases) in
  let case ft (c : case) =
    pf ft "@ @[<hv 2>| %a =>@ %a@]" p c.pat
      (fun ft () -> binding (pat_names c.pat) (fun () -> expr ctx ft c.body))
      ()
  in
  pf ft "@[<hv 2>(match %a with%a)@]" d () (fun ft -> List.iter (case ft)) cases

(** A match with guards: each case is a Lean match of its own, returning [none]
    when its pattern or guard fails, and the first case that applies gives the
    result. A last case that always applies is the default. *)
and match_ ctx ft (scruts, cases) =
  let d, p, wild = discriminants ctx (scruts, cases) in
  let alt ft (c : case) =
    let rhs = guarded ctx c in
    if irrefutable c.pat then
      pf ft "@[<hv 2>(match %a with@ | %a =>@ %a)@]" d () p c.pat rhs ()
    else
      pf ft "@[<hv 2>(match %a with@ | %a =>@ %a@ | %a => none)@]" d () p c.pat
        rhs () wild ()
  in
  let alts, default =
    match List.rev cases with
    | ({ guard = None; _ } as c) :: rest when irrefutable c.pat ->
        ( List.rev rest,
          fun ft () ->
            pf ft "@[<hv 2>(match %a with@ | %a =>@ %a)@]" d () p c.pat
              (fun ft () ->
                binding (pat_names c.pat) (fun () -> expr ctx ft c.body))
              () )
    | _ -> (cases, fun ft () -> pf ft "Inhabited.default")
  in
  match alts with
  | [] -> default ft ()
  | _ ->
      pf ft "@[<hv 2>((firstSome [%a]).getD@ %a)@]"
        (Format.pp_print_list ~pp_sep:(fun ft () -> pf ft ",@ ") alt)
        alts default ()

