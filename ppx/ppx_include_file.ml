(** [[%%include_file "f.ml"]] is the structure of [f.ml], a file next to the
    current one, as [include struct ... end]. The code generated by kanon is
    included in this way so that it is compiled along with its primitives. *)

open Ppxlib

let expand ~ctxt file =
  let loc = Expansion_context.Extension.extension_point_loc ctxt in
  let path = Filename.concat (Filename.dirname loc.loc_start.pos_fname) file in
  let str =
    try
      In_channel.with_open_bin path (fun ic ->
          let lexbuf = Lexing.from_channel ic in
          Lexing.set_filename lexbuf path;
          Parse.implementation lexbuf)
    with Sys_error e -> Location.raise_errorf ~loc "include_file: %s" e
  in
  let open Ast_builder.Default in
  pstr_include ~loc (include_infos ~loc (pmod_structure ~loc str))

let () =
  Driver.register_transformation "include_file"
    ~rules:
      [
        Context_free.Rule.extension
          (Extension.V3.declare "include_file" Extension.Context.structure_item
             Ast_pattern.(pstr (pstr_eval (estring __) nil ^:: nil))
             expand);
      ]
